      'يجب التأكيد: فصلُ ملكية الزوجين ليس من قواعد الفرائض، ولا من آيات المواريث ' +
      'ولا أحاديثها. كتبُ الفرائض لا تعرف «مالاً مشتركاً» تلقائياً — مالُ كلِّ زوج ' +
      'مالُه. ما في القانون الجزائري تحديدُ ملكيةٍ أولاً (المادة 37 من قانون الأسرة)، ' +
      'ثم يُورَّث ما خصَّ الميت. أساس هذه الشراكة في الفقه: الشركة والعرف. وتقدير ' +
      'الإسهام المادي عند النزاع من شأن قسم شؤون الأسرة — فلا تعتمد على هذه الصفحة ' +
      'وحدها.';

