      poin: [
        { teks: 'أحضر: شهادة الوفاة، دفتر العائلة أو وثائق النسب، شهادة الإرث، نُسخ ' +
          'بطاقات التعريف، وأدلة الملكية.' },
        { teks: 'يوقع جميع الورثة؛ ومن يتعذر حضوره يوكل توكيلاً موثقاً.' },
        { teks: 'من كان قاصراً يمثله وليه، ويفضل في الأموال الكبيرة اعتمادُ قرار ' +
          'للقسمة من المحكمة.' },
        { teks: 'أتعاب الموثق عادة على أساس قيمة التركة — اسأل مقدماً وقابل بين ' +
          'المكاتب.' }
      ],
